/** Bundle the server handlers (src/server/*.ts, which reuse the app's own calculation code) into api/_lib/server.mjs.
 * Vercel serves the thin files in /api as functions; files starting with "_" are not routes. Run: node scripts/build_api.mjs [--check] */
import {build} from 'esbuild';
import {readFileSync} from 'node:fs';
const out='api/_lib/server.mjs',check=process.argv.includes('--check');
const result=await build({entryPoints:['src/server/handlers.ts'],bundle:true,platform:'node',format:'esm',target:'node20',write:!check,outfile:out,legalComments:'none',
  banner:{js:'// Generated by scripts/build_api.mjs from src/server/handlers.ts. Do not edit.'}});
if(check){const fresh=new TextDecoder().decode(result.outputFiles[0].contents),old=readFileSync(out,'utf8');if(fresh!==old){console.error(`${out} is out of date: run node scripts/build_api.mjs`);process.exit(1);}console.log(`${out} is up to date`);}
else console.log('wrote',out);
